library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- =============================================================
-- ROM - CRIVO DE ERATOSTENES + TESTE DE PRIMALIDADE DE 923
-- =============================================================
-- FASE 1 (addr  0- 8): Preenche RAM[1..32] com seus proprios indices.
--                      Loop INIT_LOOP controlado com INC R1.
-- FASE 2 (addr  9-32): Elimina multiplos de 2, 3 e 5 da tabela.
-- FASE 3 (addr 33-38): Le RAM[2..32] expondo primos em R6 (out_ula).
--                      Loop READ_LOOP controlado com INC R5.
-- FASE 4 (addr 39-65): Usa os PRIMOS DA TABELA (RAM) para testar
--                      se 923 e primo por divisao por subtracao.
--                      Para cada RAM[i] != 0 (primo), divide 923 por ele.
--                      Se encontrar divisor exato: R9=0 (composto) e SAI IMEDIATAMENTE.
--                      Loop PRIME_LOOP controlado com INC R5.
--
-- INSTRUCAO INC (opcode 1010):
--   Encoding : 1010 RRRR 0000 0000 0
--   Operacao : Rd <- Rd + 1
--   Datapath : ula_entrada_a=dado_lido_r1, ula_entrada_b=x"0001", op=ADD
--
-- RESULTADO ESPERADO: 923 = 13 x 71 -> COMPOSTO -> R9=0 -> bit_debug='0'
--
-- Registradores:
--   R1 = endereco / contador geral
--   R2 = passo dos loops de eliminacao
--   R3 = 32 (limite crivo, constante)
--   R4 = 0  (constante zero)
--   R5 = ponteiro de leitura / iterador da tabela
--   R6 = valor lido da RAM (primo candidato a divisor)
--   R7 = 923 (N a testar, constante)
--   R8 = REM (resto da divisao por subtracao)
--   R9 = ISPRIME (1=primo / 0=composto) -> bit_debug
-- =============================================================
-- End | Assembly           | Binario (17 bits)       | Hex   | Descricao
-- ----|--------------------+-------------------------+-------+----------------------------
--   0 | CLR R3             | 0111_0011_0011_0000_0   | 0E660 | R3 <- 0
--   1 | ADDC R3, 32        | 0101_0011_0010_0000_0   | 0A640 | R3 = 32 (limite, fixo)
--   2 | CLR R4             | 0111_0100_0100_0000_0   | 0E880 | R4 = 0  (zero, fixo)
--   3 | CLR R1             | 0111_0001_0001_0000_0   | 0E220 | R1 <- 0
--   4 | INC R1             | 1010_0001_0000_0000_0   | 14200 | R1 = 1 (primeiro endereco)
-- --- INIT_LOOP (addr 5) -------------------------------------------------------
--   5 | SW R1, R1          | 1001_0001_0001_0000_0   | 12220 | RAM[R1] = R1
--   6 | INC R1             | 1010_0001_0000_0000_0   | 14200 | R1++ (INC contador loop)
--   7 | CMPR R1, R3        | 0110_0001_0011_0000_0   | 0C260 | R1 - 32
--   8 | BLE INIT_LOOP      | 1110_0000_0011_1110_1   | 1C07D | offset=-3 -> addr 5
-- -----------------------------------------------------------------------------
--   9 | CLR R1             | 0111_0001_0001_0000_0   | 0E220 |
--  10 | ADDC R1, 4         | 0101_0001_0000_0100_0   | 0A208 | R1=4 (2x2)
--  11 | CLR R2             | 0111_0010_0010_0000_0   | 0E440 |
--  12 | ADDC R2, 2         | 0101_0010_0000_0010_0   | 0A404 | R2=2 (passo)
-- --- ELIM_2_LOOP (addr 13) ---------------------------------------------------
--  13 | SW R4, R1          | 1001_0100_0001_0000_0   | 12820 | RAM[R1]=0
--  14 | ADD R1, R2         | 0001_0001_0010_0000_0   | 02240 | R1+=2
--  15 | CMPR R1, R3        | 0110_0001_0011_0000_0   | 0C260 | R1-32
--  16 | BLE ELIM_2_LOOP    | 1110_0000_0011_1110_1   | 1C07D | offset=-3 -> addr 13
-- -----------------------------------------------------------------------------
--  17 | CLR R1             | 0111_0001_0001_0000_0   | 0E220 |
--  18 | ADDC R1, 6         | 0101_0001_0000_0110_0   | 0A20C | R1=6 (2x3)
--  19 | CLR R2             | 0111_0010_0010_0000_0   | 0E440 |
--  20 | ADDC R2, 3         | 0101_0010_0000_0011_0   | 0A406 | R2=3 (passo)
-- --- ELIM_3_LOOP (addr 21) ---------------------------------------------------
--  21 | SW R4, R1          | 1001_0100_0001_0000_0   | 12820 | RAM[R1]=0
--  22 | ADD R1, R2         | 0001_0001_0010_0000_0   | 02240 | R1+=3
--  23 | CMPR R1, R3        | 0110_0001_0011_0000_0   | 0C260 |
--  24 | BLE ELIM_3_LOOP    | 1110_0000_0011_1110_1   | 1C07D | offset=-3 -> addr 21
-- -----------------------------------------------------------------------------
--  25 | CLR R1             | 0111_0001_0001_0000_0   | 0E220 |
--  26 | ADDC R1, 10        | 0101_0001_0000_1010_0   | 0A214 | R1=10 (2x5)
--  27 | CLR R2             | 0111_0010_0010_0000_0   | 0E440 |
--  28 | ADDC R2, 5         | 0101_0010_0000_0101_0   | 0A40A | R2=5 (passo)
-- --- ELIM_5_LOOP (addr 29) ---------------------------------------------------
--  29 | SW R4, R1          | 1001_0100_0001_0000_0   | 12820 | RAM[R1]=0
--  30 | ADD R1, R2         | 0001_0001_0010_0000_0   | 02240 | R1+=5
--  31 | CMPR R1, R3        | 0110_0001_0011_0000_0   | 0C260 |
--  32 | BLE ELIM_5_LOOP    | 1110_0000_0011_1110_1   | 1C07D | offset=-3 -> addr 29
-- -----------------------------------------------------------------------------
--  33 | CLR R5             | 0111_0101_0101_0000_0   | 0EAA0 |
--  34 | ADDC R5, 2         | 0101_0101_0000_0010_0   | 0AA04 | R5=2
-- --- READ_LOOP (addr 35) -----------------------------------------------------
--  35 | LW R6, R5          | 1000_0110_0101_0000_0   | 10CA0 | R6=RAM[R5]
--  36 | INC R5             | 1010_0101_0000_0000_0   | 14A00 | R5++ (INC contador)
--  37 | CMPR R5, R3        | 0110_0101_0011_0000_0   | 0CA60 | R5-32
--  38 | BLE READ_LOOP      | 1110_0000_0011_1110_1   | 1C07D | offset=-3 -> addr 35
-- =============================================================================
-- FASE 4: Teste de primalidade de 923 usando a tabela do crivo
-- =============================================================================
--  39 | CLR R7             | 0111_0111_0111_0000_0   | 0EEE0 | R7 <- 0
--  40 | ADDC R7, 255       | 0101_0111_1111_1111_0   | 0AFFE | R7=255
--  41 | ADDC R7, 255       | 0101_0111_1111_1111_0   | 0AFFE | R7=510
--  42 | ADDC R7, 255       | 0101_0111_1111_1111_0   | 0AFFE | R7=765
--  43 | ADDC R7, 158       | 0101_0111_1001_1110_0   | 0AF3C | R7=923 (N)
--  44 | CLR R9             | 0111_1001_1001_0000_0   | 0F320 | R9 <- 0
--  45 | ADDC R9, 1         | 0101_1001_0000_0001_0   | 0B202 | R9=1 (assume primo)
--  46 | CLR R5             | 0111_0101_0101_0000_0   | 0EAA0 | R5 <- 0
--  47 | ADDC R5, 2         | 0101_0101_0000_0010_0   | 0AA04 | R5=2 (inicio tabela)
-- --- PRIME_LOOP (addr 48) ----------------------------------------------------
--  48 | LW R6, R5          | 1000_0110_0101_0000_0   | 10CA0 | R6=RAM[R5] (primo?)
--  49 | CMPR R6, R4        | 0110_0110_0100_0000_0   | 0CC80 | R6-0
--  50 | BLE SKIP_DIV       | 1110_0000_0000_0100_0   | 1C008 | offset=+8->58 (R6=0,nao primo)
--  51 | MOV R8, R7         | 0100_1000_0111_0000_0   | 090E0 | R8=REM=923
-- --- DIV_LOOP (addr 52) ------------------------------------------------------
--  52 | CMPR R8, R6        | 0110_1000_0110_0000_0   | 0D0C0 | REM-D
--  53 | BPL DO_SUB         | 1101_0000_0000_0001_0   | 1A002 | offset=+2->55
--  54 | JMP DIV_END        | 1111_0000_0001_1100_1   | 1E039 | abs=57
-- --- DO_SUB (addr 55) --------------------------------------------------------
--  55 | SUB R8, R6         | 0010_1000_0110_0000_0   | 050C0 | REM=REM-D
--  56 | JMP DIV_LOOP       | 1111_0000_0001_1010_0   | 1E034 | abs=52
-- --- DIV_END (addr 57) -------------------------------------------------------
--  57 | CMPR R8, R4        | 0110_1000_0100_0000_0   | 0D080 | REM-0
--  58 | BLE FOUND_DIV      | 1110_0000_0000_0001_0   | 1C002 | offset=+2->60
-- --- SKIP_DIV (addr 59) ------------------------------------------------------
--  59 | JMP NEXT_PRIME     | 1111_0000_0011_1110_0   | 1E07C | abs=62
-- --- FOUND_DIV (addr 60) -----------------------------------------------------
--  60 | CLR R9             | 0111_1001_1001_0000_0   | 0F320 | R9=0 (composto)
--  61 | JMP HALT           | 1111_0000_0010_0000_1   | 1E041 | abs=65 (sai imediatamente!)
-- --- NEXT_PRIME (addr 62) ---------------------------------------------------
--  62 | INC R5             | 1010_0101_0000_0000_0   | 14A00 | R5++ (INC contador)
--  63 | CMPR R5, R3        | 0110_0101_0011_0000_0   | 0CA60 | R5-32
--  64 | BLE PRIME_LOOP     | 1110_0000_0011_1000_0   | 1C070 | offset=-16->48
-- --- HALT (addr 65) ----------------------------------------------------------
--  65 | JMP HALT           | 1111_0000_0010_0000_1   | 1E041 | trava PC=65
-- =============================================================

entity rom is
    port(
        endereco : in  unsigned(6 downto 0);
        dado     : out unsigned(16 downto 0)
    );
end entity;

architecture a_rom of rom is
    type mem is array (0 to 127) of unsigned(16 downto 0);
    constant conteudo_rom : mem := (

        -- =========================================================
        -- FASE 1: Inicializa RAM[1..32] com indices
        -- Loop INIT_LOOP usa INC R1 como contador
        -- =========================================================
        0  => B"0111_0011_0011_0000_0",  -- CLR R3
        1  => B"0101_0011_0010_0000_0",  -- ADDC R3, 32       ; R3=32 (limite, fixo)
        2  => B"0111_0100_0100_0000_0",  -- CLR R4            ; R4=0  (zero, fixo)
        3  => B"0111_0001_0001_0000_0",  -- CLR R1
        4  => B"1010_0001_0000_0000_0",  -- INC R1            ; R1=1 (primeiro endereco)
        -- INIT_LOOP:
        5  => B"1001_0001_0001_0000_0",  -- SW R1, R1         ; RAM[R1]=R1
        6  => B"1010_0001_0000_0000_0",  -- INC R1            ; R1++ (INC contador loop)
        7  => B"0110_0001_0011_0000_0",  -- CMPR R1, R3       ; R1-32
        8  => B"1110_0000_0011_1110_1",  -- BLE INIT_LOOP     ; offset=-3 -> addr 5

        -- =========================================================
        -- FASE 2a: Elimina multiplos de 2
        -- =========================================================
        9  => B"0111_0001_0001_0000_0",  -- CLR R1
        10 => B"0101_0001_0000_0100_0",  -- ADDC R1, 4        ; R1=4 (2x2)
        11 => B"0111_0010_0010_0000_0",  -- CLR R2
        12 => B"0101_0010_0000_0010_0",  -- ADDC R2, 2        ; R2=2 (passo)
        -- ELIM_2_LOOP:
        13 => B"1001_0100_0001_0000_0",  -- SW R4, R1         ; RAM[R1]=0
        14 => B"0001_0001_0010_0000_0",  -- ADD R1, R2        ; R1+=2
        15 => B"0110_0001_0011_0000_0",  -- CMPR R1, R3       ; R1-32
        16 => B"1110_0000_0011_1110_1",  -- BLE ELIM_2_LOOP   ; offset=-3 -> addr 13

        -- =========================================================
        -- FASE 2b: Elimina multiplos de 3
        -- =========================================================
        17 => B"0111_0001_0001_0000_0",  -- CLR R1
        18 => B"0101_0001_0000_0110_0",  -- ADDC R1, 6        ; R1=6 (2x3)
        19 => B"0111_0010_0010_0000_0",  -- CLR R2
        20 => B"0101_0010_0000_0011_0",  -- ADDC R2, 3        ; R2=3 (passo)
        -- ELIM_3_LOOP:
        21 => B"1001_0100_0001_0000_0",  -- SW R4, R1         ; RAM[R1]=0
        22 => B"0001_0001_0010_0000_0",  -- ADD R1, R2        ; R1+=3
        23 => B"0110_0001_0011_0000_0",  -- CMPR R1, R3       ; R1-32
        24 => B"1110_0000_0011_1110_1",  -- BLE ELIM_3_LOOP   ; offset=-3 -> addr 21

        -- =========================================================
        -- FASE 2c: Elimina multiplos de 5
        -- =========================================================
        25 => B"0111_0001_0001_0000_0",  -- CLR R1
        26 => B"0101_0001_0000_1010_0",  -- ADDC R1, 10       ; R1=10 (2x5)
        27 => B"0111_0010_0010_0000_0",  -- CLR R2
        28 => B"0101_0010_0000_0101_0",  -- ADDC R2, 5        ; R2=5 (passo)
        -- ELIM_5_LOOP:
        29 => B"1001_0100_0001_0000_0",  -- SW R4, R1         ; RAM[R1]=0
        30 => B"0001_0001_0010_0000_0",  -- ADD R1, R2        ; R1+=5
        31 => B"0110_0001_0011_0000_0",  -- CMPR R1, R3       ; R1-32
        32 => B"1110_0000_0011_1110_1",  -- BLE ELIM_5_LOOP   ; offset=-3 -> addr 29

        -- =========================================================
        -- FASE 3: Exibe primos em R6/out_ula
        -- Loop READ_LOOP usa INC R5 como contador
        -- =========================================================
        33 => B"0111_0101_0101_0000_0",  -- CLR R5
        34 => B"0101_0101_0000_0010_0",  -- ADDC R5, 2        ; R5=2
        -- READ_LOOP:
        35 => B"1000_0110_0101_0000_0",  -- LW R6, R5         ; R6=RAM[R5]
        36 => B"1010_0101_0000_0000_0",  -- INC R5            ; R5++ (INC contador loop)
        37 => B"0110_0101_0011_0000_0",  -- CMPR R5, R3       ; R5-32
        38 => B"1110_0000_0011_1110_1",  -- BLE READ_LOOP     ; offset=-3 -> addr 35

        -- =========================================================
        -- FASE 4: Teste de primalidade de 923 usando a tabela
        --   Percorre RAM[2..32]: se RAM[i]!=0 (primo), divide 923 por ele
        --   Se resto=0: achou divisor -> R9=0 (composto)
        --   Loop PRIME_LOOP usa INC R5 como contador
        -- =========================================================
        39 => B"0111_0111_0111_0000_0",  -- CLR R7
        40 => B"0101_0111_1111_1111_0",  -- ADDC R7, 255      ; R7=255
        41 => B"0101_0111_1111_1111_0",  -- ADDC R7, 255      ; R7=510
        42 => B"0101_0111_1111_1111_0",  -- ADDC R7, 255      ; R7=765
        43 => B"0101_0111_1001_1110_0",  -- ADDC R7, 158      ; R7=923 (N)
        44 => B"0111_1001_1001_0000_0",  -- CLR R9
        45 => B"0101_1001_0000_0001_0",  -- ADDC R9, 1        ; R9=1 (assume primo)
        46 => B"0111_0101_0101_0000_0",  -- CLR R5
        47 => B"0101_0101_0000_0010_0",  -- ADDC R5, 2        ; R5=2 (inicio tabela)

        -- PRIME_LOOP:
        48 => B"1000_0110_0101_0000_0",  -- LW R6, R5         ; R6=RAM[R5] (primo candidato)
        49 => B"0110_0110_0100_0000_0",  -- CMPR R6, R4       ; R6-0 (e primo?)
        50 => B"1110_0000_0000_0100_0",  -- BLE SKIP_DIV      ; offset=+8->58 (R6=0: pula)
        51 => B"0100_1000_0111_0000_0",  -- MOV R8, R7        ; R8=REM=923

        -- DIV_LOOP:
        52 => B"0110_1000_0110_0000_0",  -- CMPR R8, R6       ; REM-D
        53 => B"1101_0000_0000_0001_0",  -- BPL DO_SUB        ; offset=+2->55 (REM>=D)
        54 => B"1111_0000_0001_1100_1",  -- JMP DIV_END       ; abs=57 (REM<D: fim div)

        -- DO_SUB:
        55 => B"0010_1000_0110_0000_0",  -- SUB R8, R6        ; REM=REM-D
        56 => B"1111_0000_0001_1010_0",  -- JMP DIV_LOOP      ; abs=52

        -- DIV_END:
        57 => B"0110_1000_0100_0000_0",  -- CMPR R8, R4       ; REM-0
        58 => B"1110_0000_0000_0001_0",  -- BLE FOUND_DIV     ; offset=+2->60 (REM=0: divisivel)

        -- SKIP_DIV (R6=0 nao e primo, ou nao achou divisor):
        59 => B"1111_0000_0001_1111_0",  -- JMP NEXT_PRIME    ; abs=62

        -- FOUND_DIV:
        60 => B"0111_1001_1001_0000_0",  -- CLR R9            ; R9=0 (composto)
        61 => B"1111_0000_0010_0000_1",  -- JMP HALT          ; abs=65 (sai imediatamente!)

        -- NEXT_PRIME:
        62 => B"1010_0101_0000_0000_0",  -- INC R5            ; R5++ (INC contador loop)
        63 => B"0110_0101_0011_0000_0",  -- CMPR R5, R3       ; R5-32
        64 => B"1110_0000_0011_1000_0",  -- BLE PRIME_LOOP    ; offset=-16->48

        -- HALT:
        65 => B"1111_0000_0010_0000_1",  -- JMP HALT          ; trava PC=65

        others => (others => '0')
    );
begin
    dado <= conteudo_rom(to_integer(endereco));
end architecture;

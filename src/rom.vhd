library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- =============================================================
-- ROM LAB 7 - MEMÓRIA DE DADOS
-- =============================================================
-- End | Assembly        | Binario (17 bits)     | Descricao
-- ----|-----------------|-----------------------|-----------------------------------
--  0  | SUB R1, R1      | 0010 0001 0001 0000 0 | Zera R1 (R1 <- R1 - R1)
--  1  | LI R1, 32       | 0101 0001 00100000 0  | R1 = R1 + 32 -> Endereco 32
--  2  | SUB R2, R2      | 0010 0010 0010 0000 0 | Zera R2 
--  3  | LI R2, 64       | 0101 0010 01000000 0  | R2 = R2 + 64 -> Endereco 64
--  4  | SUB R3, R3      | 0010 0011 0011 0000 0 | Zera R3 
--  5  | LI R3, 170      | 0101 0011 10101010 0  | R3 = Dado 170 (0xAA)
--  6  | SUB R4, R4      | 0010 0100 0100 0000 0 | Zera R4 
--  7  | LI R4, 85       | 0101 0100 01010101 0  | R4 = Dado 85 (0x55)
--     |                 |                       |
--  8  | SW R3, R1       | 1001 0011 0001 0000 0 | RAM[32] = 170
--  9  | SW R4, R2       | 1001 0100 0010 0000 0 | RAM[64] =  85
--     |                 |                       |
--  10 | SUB R5, R5      | 0010 0101 0101 0000 0 | Zera R5 
--  11 | LI R5, 32       | 0101 0101 00100000 0  | R5 = Endereco 32 (Leitura)
--  12 | SUB R6, R6      | 0010 0110 0110 0000 0 | Zera R6 
--  13 | LI R6, 64       | 0101 0110 01000000 0  | R6 = Endereco 64 (Leitura)
--     |                 |                       |
--  14 | LW R7, R5       | 1000 0111 0101 0000 0 | R7 = RAM[32] (Deve ser 170)
--  15 | LW R8, R6       | 1000 1000 0110 0000 0 | R8 = RAM[64] (Deve ser 85)
--  16 | JMP 16          | 1111 000000 0010000   | Loop infinito (endereço 16 absoluto)
-- =============================================================

entity rom is
    port(
        endereco : in  unsigned(6 downto 0);
        dado     : out unsigned(16 downto 0)
    );
end entity;

architecture a_rom of rom is
    type mem is array (0 to 127) of unsigned(16 downto 0);
    constant conteudo_rom : mem := (
        0  => B"0010_0001_0001_0000_0",
        1  => B"0101_0001_00100000_0",
        
        2  => B"0010_0010_0010_0000_0",
        3  => B"0101_0010_01000000_0",
        
        4  => B"0010_0011_0011_0000_0",
        5  => B"0101_0011_10101010_0",
        
        6  => B"0010_0100_0100_0000_0",
        7  => B"0101_0100_01010101_0",
        
        8  => B"1001_0011_0001_0000_0",
        9  => B"1001_0100_0010_0000_0",
        
        10 => B"0010_0101_0101_0000_0",
        11 => B"0101_0101_00100000_0",
        
        12 => B"0010_0110_0110_0000_0",
        13 => B"0101_0110_01000000_0",
        
        14 => B"1000_0111_0101_0000_0",
        15 => B"1000_1000_0110_0000_0",
        
        16 => B"1111_000000_0010000",
        
        others => (others => '0')
    );
begin
    dado <= conteudo_rom(to_integer(endereco));
end architecture;